# MULTIBAGGER RADAR™
# ============================================================
def calculate_multibagger_score(row, alpha_score):
    """
    Simple MVP multibagger score: 0-100.

    This is deliberately NOT a prediction of a future share price.
    It identifies companies with a combination of:
      - earnings growth
      - sales growth
      - reasonable valuation
      - ROE/business quality
      - manageable debt
      - catalysts
      - smaller market-cap opportunity

    Maximum:
      Growth:       25
      Quality:      15
      Valuation:    15
      Financial:    10
      Catalyst:     10
      Size:          10
      AlphaScore:   15
      Total:       100
    """

    # Growth: EPS growth 0-25
    eps = row["eps_growth"]
    if pd.isna(eps):
        growth_points = 0
    elif eps >= 30:
        growth_points = 25
    elif eps >= 25:
        growth_points = 22
    elif eps >= 20:
        growth_points = 19
    elif eps >= 15:
        growth_points = 15
    elif eps >= 10:
        growth_points = 10
    elif eps >= 5:
        growth_points = 5
    else:
        growth_points = 0

    # Sales growth 0-10 inside growth category
    sales = row["sales_growth"]
    if pd.isna(sales):
        sales_points = 0
    elif sales >= 30:
        sales_points = 10
    elif sales >= 20:
        sales_points = 8
    elif sales >= 10:
        sales_points = 6
    elif sales >= 5:
        sales_points = 3
    else:
        sales_points = 0

    # To keep growth at 25, combine EPS and sales using weighted average
    growth_points = round(
        min(25, growth_points * 0.70 + sales_points * 0.30)
    )

    # Quality 15
    roe = row["roe"]
    if pd.isna(roe):
        quality_points = 0
    elif roe >= 25:
        quality_points = 15
    elif roe >= 20:
        quality_points = 13
    elif roe >= 15:
        quality_points = 10
    elif roe >= 10:
        quality_points = 6
    elif roe >= 5:
        quality_points = 3
    else:
        quality_points = 0

    # Valuation 15
    pe = row["pe"]
    if pd.isna(pe) or pe <= 0:
        valuation_points = 0
    elif pe <= 6:
        valuation_points = 15
    elif pe <= 8:
        valuation_points = 13
    elif pe <= 10:
        valuation_points = 11
    elif pe <= 15:
        valuation_points = 7
    elif pe <= 20:
        valuation_points = 3
    else:
        valuation_points = 0

    # Financial strength 10
    debt = row["debt_ratio"]
    if pd.isna(debt):
        financial_points = 0
    elif debt < 0:
        financial_points = 10
    elif debt <= 1:
        financial_points = 9
    elif debt <= 2:
        financial_points = 7
    elif debt <= 3:
        financial_points = 5
    elif debt <= 4:
        financial_points = 2
    else:
        financial_points = 0

    # Catalyst 10
    catalyst = row["catalyst_score"]
    catalyst_points = (
        0
        if pd.isna(catalyst)
        else max(0, min(10, float(catalyst) * 2))
    )

    # Size 10
    market_cap = row["market_cap_billion"]
    if pd.isna(market_cap):
        size_points = 0
    elif market_cap <= 5:
        size_points = 10
    elif market_cap <= 10:
        size_points = 9
    elif market_cap <= 20:
        size_points = 7
    elif market_cap <= 40:
        size_points = 5
    elif market_cap <= 100:
        size_points = 2
    else:
        size_points = 0

    # AlphaScore contribution 15
    alpha_points = round((alpha_score / 100) * 15)

    total = round(
        growth_points
        + quality_points
        + valuation_points
        + financial_points
        + catalyst_points
        + size_points
        + alpha_points
    )

    return max(0, min(100, total))


def get_multibagger_rating(score):
    if score >= 80:
        return "High Potential", "🟢"
    if score >= 70:
        return "Promising", "🟢"
    if score >= 60:
        return "Watchlist", "🟡"
    if score >= 50:
        return "Speculative", "🟠"
    return "Low Potential", "🔴"


