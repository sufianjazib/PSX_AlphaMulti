def score_eps_growth(value):
    if pd.isna(value):
        return 0
    if value > 30:
        return 25
    if value >= 20:
        return 20
    if value >= 10:
        return 15
    if value >= 5:
        return 10
    if value >= 0:
        return 5
    return 0


def score_roe(value):
    if pd.isna(value):
        return 0
    if value > 25:
        return 20
    if value >= 20:
        return 17
    if value >= 15:
        return 14
    if value >= 10:
        return 10
    if value >= 5:
        return 5
    return 0


def score_debt(value):
    # Net Debt / EBITDA
    if pd.isna(value):
        return 0
    if value < 0:
        return 20
    if value <= 1:
        return 18
    if value <= 2:
        return 15
    if value <= 3:
        return 10
    if value <= 4:
        return 5
    return 0


def score_pe(value):
    if pd.isna(value) or value <= 0:
        return 0
    if value < 5:
        return 20
    if value <= 7:
        return 17
    if value <= 10:
        return 14
    if value <= 15:
        return 10
    if value <= 20:
        return 5
    return 0


def score_dividend_and_catalyst(dividend_yield, catalyst_score):
    if pd.isna(dividend_yield):
        dividend_points = 0
    elif dividend_yield >= 10:
        dividend_points = 10
    elif dividend_yield >= 7:
        dividend_points = 8
    elif dividend_yield >= 5:
        dividend_points = 6
    elif dividend_yield >= 3:
        dividend_points = 4
    elif dividend_yield > 0:
        dividend_points = 2
    else:
        dividend_points = 0

    catalyst_points = (
        0
        if pd.isna(catalyst_score)
        else max(0, min(5, float(catalyst_score)))
    )

    return dividend_points + catalyst_points


def calculate_alpha_score(row):
    growth = score_eps_growth(row["eps_growth"])
    quality = score_roe(row["roe"])
    financial = score_debt(row["debt_ratio"])
    valuation = score_pe(row["pe"])
    dividend_catalyst = score_dividend_and_catalyst(
        row["dividend_yield"],
        row["catalyst_score"],
    )

    total = round(
        growth + quality + financial + valuation + dividend_catalyst
    )

    return {
        "growth": growth,
        "quality": quality,
        "financial": financial,
        "valuation": valuation,
        "dividend_catalyst": dividend_catalyst,
        "total": max(0, min(100, total)),
    }


def get_rating(score):
    if score >= 90:
        return "Exceptional", "🟢"
    if score >= 80:
        return "Strong", "🟢"
    if score >= 70:
        return "Attractive", "🟢"
    if score >= 60:
        return "Watch", "🟡"
    if score >= 50:
        return "Weak", "🟠"
    return "Avoid", "🔴"


